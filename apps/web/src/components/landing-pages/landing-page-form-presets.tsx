export type LandingPageFormPreset = {
  id: string;
  label: string;
  group: LandingPageFormGroupId;
  headline: string;
  subheadline?: string;
  submitLabel: string;
  footerText?: string;
  formTheme: LandingPageFormTheme;
  fields: Omit<LandingPageLeadFormField, 'id'>[];
  /** Compact preview colors for graphics rail */
  preview: { bg: string; accent: string };
};

const FOOTER = 'Thông tin của bạn được bảo mật. Không gửi mật khẩu.';

function f(
  name: string,
  label: string,
  fieldType: LandingPageLeadFormField['fieldType'],
  opts?: Partial<Omit<LandingPageLeadFormField, 'id' | 'name' | 'label' | 'fieldType'>>,
): Omit<LandingPageLeadFormField, 'id'> {
  return {
    name,
    label,
    fieldType,
    required: opts?.required ?? false,
    placeholder: opts?.placeholder,
    options: opts?.options,
    optionsLayout: opts?.optionsLayout,
  };
}

