export function getButtonLibraryTemplate(id: string): LpButtonLibraryTemplate | null {
  return LP_BUTTON_LIBRARY_TEMPLATES.find((t) => t.id === id) || null;
}

export function buttonLibraryTemplateToPreset(
  tpl: LpButtonLibraryTemplate,
): LandingPageButtonPreset {
  return {
    id: tpl.id,
    label: tpl.label,
    style: { ...tpl.style },
  };
}

export function searchButtonLibraryTemplates(
  query: string,
  category: LpButtonLibraryCategoryId | 'all',
): LpButtonLibraryTemplate[] {
  const q = query.trim().toLowerCase();
  return LP_BUTTON_LIBRARY_TEMPLATES.filter((t) => {
    if (category !== 'all' && t.category !== category) return false;
    if (!q) return true;
    return (
      t.id.toLowerCase().includes(q) ||
      t.label.toLowerCase().includes(q) ||
      t.category.includes(q) ||
      (t.style.background || '').toLowerCase().includes(q)
    );
  });
}

export function countButtonLibraryByCategory(category: LpButtonLibraryCategoryId): number {
  return LP_BUTTON_LIBRARY_TEMPLATES.filter((t) => t.category === category).length;
}
