/** Applied ONLY while generating the canonical catalog, before any new draft is created. */
export function localizeVietnameseTemplate(
  template: LandingPageTemplateDefinition,
): LandingPageTemplateDefinition {
  const category = template.category as LandingPageCategory;
  const copy = TEMPLATE_INDUSTRY_COPY_VI[category];
  if (!copy) return template;
  const suffix = template.name.split(' · ').slice(1).join(' · ');
  const localizedSuffix =
    VIETNAMESE_INDUSTRY_VARIANT_NAMES[category]?.[suffix] ||
    VARIANT_LABELS[suffix] ||
    vietnameseTemplateText(suffix, category);
  const name =
    template.slug !== VIETNAMESE_PRIMARY_SLUGS[category] && suffix && localizedSuffix !== copy.title
      ? `${copy.title} · ${localizedSuffix}`
      : copy.title;
  const description =
    template.slug === VIETNAMESE_PRIMARY_SLUGS[category] || !localizedSuffix
      ? copy.description
      : `${copy.description} Tập trung vào ${localizedSuffix.charAt(0).toLocaleLowerCase('vi-VN') + localizedSuffix.slice(1)}.`;
  const metaDescription =
    description.length <= 160
      ? description
      : `${description.slice(0, 157).replace(/\s+\S*$/, '')}…`;
  const blocks = localizeNode(template.spec.blocks, category) as typeof template.spec.blocks;
  const primary = VIETNAMESE_PRIMARY_HERO[category];
  if (primary && template.slug === VIETNAMESE_PRIMARY_SLUGS[category]) {
    const hero = blocks.find((block) => block.type === 'Hero');
    if (hero) Object.assign(hero, localizeNode(primary, category));
  }
  for (const block of blocks) {
    if (
      block.type === 'Footer' &&
      !/minh họa|bản mẫu/i.test([block.body, block.subheadline].join(' '))
    ) {
      block.body = vietnameseTemplateText(
        [block.body, 'Bản mẫu · Nội dung minh họa'].filter(Boolean).join(' · '),
        category,
      );
    }
    if (block.type === 'Testimonials') {
      block.headline = 'Nội dung đánh giá minh họa';
      block.items = block.items.map((item) => ({
        ...item,
        author: 'Khách hàng mẫu',
        role: 'Nội dung minh họa',
      }));
    }
  }
  return {
    ...template,
    thumbnail: `/landing-page-previews/catalog-vi-v1/${template.slug}-thumb.jpg`,
    previewLongImage: `/landing-page-previews/catalog-vi-v1/${template.slug}-long.jpg`,
    name,
    description,
    spec: {
      ...template.spec,
      blocks,
      meta: {
        ...template.spec.meta,
        templateCopyVersion: 'vi-VN-v1',
        gallery: {
          ...template.spec.meta?.gallery,
          thumbnail: `/landing-page-previews/catalog-vi-v1/${template.slug}-thumb.jpg`,
          previewLongImage: `/landing-page-previews/catalog-vi-v1/${template.slug}-long.jpg`,
        },
      },
      seo: {
        ...template.spec.seo,
        title: name,
        metaDescription,
        ogImage: `/landing-page-previews/catalog-vi-v1/${template.slug}-thumb.jpg`,
      },
    },
  };
}
