// Catalog generation repeats the same copy across variants. Keep this cache bounded
// and creation-only so importing the catalog does not repeat every terminology scan.
const localizedTextCache = new Map<string, string>();

function reviewedVietnameseSentence(text: string): string {
  let value = text;
  for (let step = 0; step < 8; step++) {
    const next = VIETNAMESE_FINAL_COPY[value];
    if (!next || next === value) return value;
    value = next;
  }
  return value;
}

export function vietnameseTemplateText(text: string, category: LandingPageCategory): string {
  if (VIETNAMESE_FINAL_COPY[text]) return reviewedVietnameseSentence(text);
  if (!text || /(?:https?:\/\/|mailto:|tel:)|^[^\s@]+@[^\s@]+$/.test(text)) return text;
  const cacheKey = `${category}\u0000${text}`;
  const cached = localizedTextCache.get(cacheKey);
  if (cached !== undefined) return cached;
  let value = VIETNAMESE_EDITORIAL_COPY[text] ?? text;
  if (category === 'real_estate') value = value.replace(/\bstudio\b/gi, 'căn hộ một không gian');
  // In the product industry "case" is the charging case; other contexts use examples.
  value = value.replace(/\bcase\s+(\d+)\b/gi, 'Hình minh họa $1');
  if (category === 'product') value = value.replace(/\bcase\b/gi, 'hộp sạc');
  for (const [pattern, replacement] of substitutions) value = value.replace(pattern, replacement);
  value = VIETNAMESE_EDITORIAL_COPY[value] ?? value;
  const sentence = value
    .replace(/[ \t]{2,}/g, ' ')
    .trim()
    .replace(
      /(^|[.!?]\s+)([\p{L}])/gu,
      (_, prefix: string, letter: string) => prefix + letter.toLocaleUpperCase('vi-VN'),
    );
  const reviewed = VIETNAMESE_SENTENCE_COPY[sentence] ?? sentence;
  const result = reviewedVietnameseSentence(reviewed);
  if (localizedTextCache.size < 20000) localizedTextCache.set(cacheKey, result);
  return result;
}

