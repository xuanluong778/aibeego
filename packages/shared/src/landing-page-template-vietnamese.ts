const OPAQUE_KEYS = new Set([
  'id',
  'type',
  'style',
  'themeTokens',
  'meta',
  'tracking',
  'settings',
  'imageStyle',
  'posterImageStyle',
  'rules',
  'validation',
  'source',
  'html',
  'customHtml',
  'customCss',
  'customJs',
]);
const TEXT_ARRAY_KEYS = new Set(['features', 'options', 'bullets', 'paragraphs', 'trustPoints']);

function localizeNode(value: unknown, category: LandingPageCategory, parentKey = ''): unknown {
  if (Array.isArray(value))
    return value.map((item) =>
      typeof item === 'string' && TEXT_ARRAY_KEYS.has(parentKey)
        ? vietnameseTemplateText(item, category)
        : localizeNode(item, category, parentKey),
    );
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.entries(value).map(([key, item]) => {
      if (OPAQUE_KEYS.has(key)) return [key, item];
      if (
        typeof item === 'string' &&
        (TEXT_KEYS.has(key) || (key === 'name' && parentKey === 'plans'))
      )
        return [key, vietnameseTemplateText(item, category)];
      return [key, localizeNode(item, category, key)];
    }),
  );
}

