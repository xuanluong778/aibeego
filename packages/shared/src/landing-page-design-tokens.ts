export type ApplyCatalogThemeTokensInput = {
  theme: LandingPageTheme;
  designFamily?: string;
  category?: LandingPageCategory | string;
  variantIndex?: number;
};

/** Catalog-time themeTokens: preset + designFamily + category industry canvas. */
export function applyCatalogThemeTokens(input: ApplyCatalogThemeTokensInput): LandingPageThemeTokens {
  const base = { ...LANDING_PAGE_THEME_PRESETS[input.theme] };
  const family = designFamilyTokenOverrides(input.designFamily);
  const category =
    input.category != null && input.variantIndex != null
      ? categoryCanvasOverrides(input.category, input.variantIndex)
      : {};
  const merged: LandingPageThemeTokens = {
    ...base,
    ...family,
    ...category,
  };
  if (!merged.canvas) merged.canvas = merged.background;
  if (!merged.surfaceAlt) merged.surfaceAlt = merged.surface;
  if (!merged.gradient) {
    merged.gradient = `linear-gradient(160deg, ${merged.surfaceAlt || merged.surface} 0%, ${merged.background} 55%, ${merged.surface} 100%)`;
  }
  if (input.category === 'agency') {
    merged.containerWidth = merged.containerWidth || '68rem';
    merged.sectionSpacing = merged.sectionSpacing || '2.35rem';
    merged.textWidth = merged.textWidth || '38rem';
    merged.shadowMd = merged.shadowMd || '0 14px 38px rgba(15, 23, 42, 0.09)';
    merged.shadowLg = merged.shadowLg || '0 24px 56px rgba(15, 23, 42, 0.14)';
    merged.lineHeightHeading = merged.lineHeightHeading ?? 1.14;
    merged.lineHeightBody = merged.lineHeightBody ?? 1.6;
    merged.radiusMd = merged.radiusMd || merged.radius;
    merged.radiusLg = merged.radiusLg || `calc(${merged.radius} + 4px)`;
  }
  return merged;
}
