/** Structural uniqueness diagnostics for gates. */
export function analyzeArchitectureUniqueness(): {
  categoryPrimarySignatures: Record<string, string>;
  primaryUnique: boolean;
  perCategoryUniqueFlows: Record<string, { unique: number; total: number; maxShare: number }>;
  globalMaxShare: number;
  globalUniqueSignatures: number;
  totalTemplates: number;
} {
  const categoryPrimarySignatures: Record<string, string> = {};
  const allSigs: string[] = [];
  const perCategoryUniqueFlows: Record<
    string,
    { unique: number; total: number; maxShare: number }
  > = {};

  for (const [cat, variants] of Object.entries(CATEGORY_ARCHITECTURES)) {
    const sigs = variants.map((v) => sectionSignature(v.sectionSequence));
    categoryPrimarySignatures[cat] = sigs[0] || '';
    allSigs.push(...sigs);
    const counts = new Map<string, number>();
    for (const s of sigs) counts.set(s, (counts.get(s) || 0) + 1);
    const max = Math.max(0, ...counts.values());
    perCategoryUniqueFlows[cat] = {
      unique: counts.size,
      total: sigs.length,
      maxShare: sigs.length ? max / sigs.length : 1,
    };
  }

  const primarySet = new Set(Object.values(categoryPrimarySignatures));
  const globalCounts = new Map<string, number>();
  for (const s of allSigs) globalCounts.set(s, (globalCounts.get(s) || 0) + 1);
  const globalMax = Math.max(0, ...globalCounts.values());

  return {
    categoryPrimarySignatures,
    primaryUnique: primarySet.size === Object.keys(categoryPrimarySignatures).length,
    perCategoryUniqueFlows,
    globalMaxShare: globalMax / allSigs.length,
    globalUniqueSignatures: globalCounts.size,
    totalTemplates: allSigs.length,
  };
}
