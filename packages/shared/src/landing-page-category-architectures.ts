function tuneHeroForArchitecture(
  from: LandingPageBlock[],
  arch: CategoryArchitectureVariant,
  category: string,
): LandingPageBlock {
  const hero = pickBlock(from, 'Hero');
  const copy = CTA_COPY[arch.ctaStrategy];
  const heroVariant = resolveBlockVariant(
    'Hero',
    arch.blockVariants?.Hero || mapLegacyHeroVariant(arch.heroVariant),
  );
  const base = hero
    ? cloneBlock(hero, arch.architectureId)
    : ({
        id: uid('hero', 1),
        type: 'Hero' as const,
        enabled: true,
        spacing: 'lg' as const,
        headline: 'Headline mạnh mẽ',
        subheadline: 'Subheadline chuyển đổi',
        ctaLabel: copy.ctaLabel,
        ctaUrl: '#lead-form',
        imageUrl: null,
      } satisfies LandingPageBlock);

  let next: LandingPageBlock = {
    ...base,
    type: 'Hero',
    variant: heroVariant,
    ctaLabel: copy.ctaLabel,
    ctaUrl: '#lead-form',
  };

  if (category === 'webinar' || arch.layout === 'webinar' || arch.heroVariant === 'countdown') {
    next = {
      ...next,
      eventDate: (base as { eventDate?: string }).eventDate || 'Thứ 5 · tuần này',
      eventTime: (base as { eventTime?: string }).eventTime || '19:30 – 21:00',
      eventFormat: (base as { eventFormat?: string }).eventFormat || 'Online · Zoom',
      trustPoints:
        (base as { trustPoints?: string[] }).trustPoints ||
        ['Framework áp dụng ngay', 'Case study thực tế', 'Tài liệu kèm theo'],
    };
  }

  // Legacy hero tokens + foundation ids share behavioral hooks for copy density.
  const layoutHint = heroVariant;
  if (
    arch.heroVariant === 'split' ||
    arch.heroVariant === 'portrait' ||
    layoutHint === 'split-left' ||
    layoutHint === 'split-right'
  ) {
    next = {
      ...next,
      trustPoints: (next as { trustPoints?: string[] }).trustPoints || [
        'Uy tín rõ ràng',
        'Quy trình minh bạch',
        'Hỗ trợ nhanh',
      ],
      body: undefined,
    };
  }

  if (arch.heroVariant === 'minimal' || layoutHint === 'minimal-copy') {
    next = {
      ...next,
      spacing: 'lg',
      subheadline: ((next as { subheadline?: string }).subheadline || '').slice(0, 120),
    };
  }

  if (arch.heroVariant === 'visual_first' || layoutHint === 'fullscreen-image') {
    next = {
      ...next,
      body: (next as { body?: string }).body || 'Visual-first · trải nghiệm trước, quyết định sau',
    };
  }

  if (arch.heroVariant === 'form_embed' || layoutHint === 'floating-card') {
    next = {
      ...next,
      body: (next as { body?: string }).body || 'Điền form bên dưới — phản hồi nhanh',
      spacing: 'md',
    };
  }

  return next;
}

function applyProofHeadlines(block: LandingPageBlock, proof: ProofType): LandingPageBlock {
  if (block.type === 'Testimonials') {
    const map: Partial<Record<ProofType, string>> = {
      case_kpi: 'Case study & KPI',
      reviews: 'Khách hàng nói gì',
      portfolio: 'Dự án tiêu biểu',
      speaker: 'Được tin tưởng bởi',
    };
    return { ...block, headline: map[proof] || block.headline || 'Social proof' };
  }
  if (block.type === 'Guarantee') {
    const map: Partial<Record<ProofType, string>> = {
      certificate: 'Chứng chỉ & cam kết',
      amenities: 'Pháp lý & cam kết',
      case_kpi: 'Cam kết KPI',
    };
    return { ...block, headline: map[proof] || block.headline || 'Cam kết' };
  }
  if (block.type === 'Gallery' && proof === 'before_after') {
    return { ...block, headline: 'Before / After', subheadline: 'Kết quả thực tế' };
  }
  if (block.type === 'Features' && proof === 'integrations') {
    return { ...block, headline: 'Tích hợp & kết nối' };
  }
  if (block.type === 'Benefits' && proof === 'amenities') {
    return { ...block, headline: 'Tiện ích nổi bật' };
  }
  if (block.type === 'Product' && proof === 'menu') {
    return { ...block, headline: 'Thực đơn / danh mục' };
  }
  return block;
}

