/**
 * Architecture recipe authoring record (per category × variant).
 * `designFamily` / `conversionGoal` / `blockVariants` / `purpose` may be omitted —
 * `v()` fills them from legacy fields so existing CATEGORY_ARCHITECTURES stay valid.
 */
export type CategoryArchitectureVariant = {
  variantIndex: number;
  /** Slug suffix compatible with gallery images ('' | trust | pricing | …). */
  flowSlugSuffix: string;
  architectureId: string;
  label: string;
  nameSuffix: string;
  descriptionHint: string;
  /** @deprecated Use blockVariants.Hero (foundation ids). Kept for AI/gates. */
  heroVariant: HeroVariant;
  sectionSequence: ArchitectureSection[];
  ctaStrategy: CtaStrategy;
  formPlacement: FormPlacement;
  proofType: ProofType;
  visualComposition: VisualComposition;
  theme: LandingPageTheme;
  layout: LandingPageLayout;
  badges: LandingPageTemplateBadge[];
  /** Foundation fields — filled by `v()` when omitted. */
  designFamily: LandingPageDesignFamily;
  conversionGoal: LandingPageConversionGoal;
  purpose: string;
  blockVariants: Partial<Record<LandingPageBlock['type'], string>>;
};

const SUFFIX = [
  '',
  'trust',
  'pricing',
  'process',
  'gallery',
  'video',
  'faq',
  'split',
  'form',
  'minimal',
] as const;

const NAME = [
  '',
  '· Trust First',
  '· Pricing First',
  '· Process Story',
  '· Gallery',
  '· Video',
  '· FAQ Heavy',
  '· Split Hero',
  '· Early Form',
  '· Minimal',
] as const;

type ArchitectureAuthoring = Omit<
  CategoryArchitectureVariant,
  | 'variantIndex'
  | 'flowSlugSuffix'
  | 'nameSuffix'
  | 'label'
  | 'designFamily'
  | 'conversionGoal'
  | 'purpose'
  | 'blockVariants'
> & {
  label?: string;
  designFamily?: LandingPageDesignFamily;
  conversionGoal?: LandingPageConversionGoal;
  purpose?: string;
  blockVariants?: Partial<Record<LandingPageBlock['type'], string>>;
  /** Override gallery slug suffix (default = SUFFIX[index]). */
  flowSlugSuffix?: string;
  nameSuffix?: string;
};

function v(index: number, partial: ArchitectureAuthoring): CategoryArchitectureVariant {
  const designFamily =
    partial.designFamily ||
    inferDesignFamily({
      theme: partial.theme,
      layout: partial.layout,
      visualComposition: partial.visualComposition,
    });
  const conversionGoal =
    partial.conversionGoal || mapCtaStrategyToConversionGoal(partial.ctaStrategy);
  const purpose = partial.purpose || partial.descriptionHint || partial.architectureId;
  const blockVariants: Partial<Record<LandingPageBlock['type'], string>> = {
    Hero: mapLegacyHeroVariant(partial.heroVariant),
    ...(partial.blockVariants || {}),
  };
  // Normalize known keys
  for (const [k, val] of Object.entries(blockVariants)) {
    blockVariants[k as LandingPageBlock['type']] = resolveBlockVariant(
      k as LandingPageBlock['type'],
      val,
    );
  }

  const { flowSlugSuffix: flowOverride, nameSuffix: nameOverride, ...rest } = partial;

  return {
    variantIndex: index,
    label: partial.label || partial.architectureId,
    ...rest,
    flowSlugSuffix: flowOverride ?? SUFFIX[index] ?? '',
    nameSuffix: nameOverride ?? NAME[index] ?? '',
    designFamily,
    conversionGoal,
    purpose,
    blockVariants,
  };
}

/** Build stamped recipe from a category architecture (expand / select). */
export function architectureVariantToRecipe(
  arch: CategoryArchitectureVariant,
  category?: LandingPageCategory | string,
): LandingPageArchitectureRecipe {
  return buildArchitectureRecipe({
    architectureId: arch.architectureId,
    purpose: arch.purpose,
    designFamily:
      arch.designFamily ||
      inferDesignFamily({
        theme: arch.theme,
        layout: arch.layout,
        visualComposition: arch.visualComposition,
        category,
      }),
    conversionGoal: arch.conversionGoal,
    flow: String(flowIdFromSlugSuffix(arch.flowSlugSuffix)),
    sectionSequence: arch.sectionSequence,
    blockVariants: arch.blockVariants,
    heroVariant: arch.heroVariant,
    ctaStrategy: arch.ctaStrategy,
    formPlacement: arch.formPlacement,
    proofType: arch.proofType,
    visualComposition: arch.visualComposition,
    theme: arch.theme,
    layout: arch.layout,
  });
}

