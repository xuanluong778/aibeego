function stampCategoryArchitectures(
  raw: Record<LandingPageCategory, CategoryArchitectureVariant[]>,
): Record<LandingPageCategory, CategoryArchitectureVariant[]> {
  stampArchitecturesFromVisualDna(raw);
  const out = {} as Record<LandingPageCategory, CategoryArchitectureVariant[]>;
  for (const cat of Object.keys(raw) as LandingPageCategory[]) {
    out[cat] = raw[cat].map((arch) => ({
      ...arch,
      blockVariants: resolveCategoryBlockVariants(cat, {
        variantIndex: arch.variantIndex,
        sectionSequence: arch.sectionSequence,
        ctaStrategy: arch.ctaStrategy,
        heroVariant: arch.heroVariant,
        blockVariants: arch.blockVariants,
        visualComposition: arch.visualComposition,
      }),
    }));
  }
  return out;
}

export const CATEGORY_ARCHITECTURES = stampCategoryArchitectures(RAW_CATEGORY_ARCHITECTURES);

export function sectionSignature(sequence: ArchitectureSection[]): string {
  return sequence.join('>');
}

export function getCategoryArchitectures(
  category: LandingPageCategory | string,
): CategoryArchitectureVariant[] {
  return CATEGORY_ARCHITECTURES[category as LandingPageCategory] || CATEGORY_ARCHITECTURES.product;
}

